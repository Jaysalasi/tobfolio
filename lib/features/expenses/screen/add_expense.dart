import 'package:tob/features/expenses/model/expenses_model.dart';
import 'package:tob/features/home/bloc/home_bloc.dart';

class AddExpenseScreen extends StatefulWidget {
  const AddExpenseScreen({super.key});

  @override
  State<AddExpenseScreen> createState() => _AddExpenseScreenState();
}

class _AddExpenseScreenState extends State<AddExpenseScreen> {
  PropertyModel? selectedProperty;
  String? selectedUnit;
  String? selectedExpenseType;
  final TextEditingController _costController = TextEditingController();
  final TextEditingController _descriptionController = TextEditingController();
  bool _isSubmitting = false;

  @override
  void initState() {
    super.initState();
    // Initialize with first property if available
    context.read<AllPropertyBloc>().add(LoadProperties());
     context.read<HomeBloc>().add(LoadHomeData());
  }

  @override
  void dispose() {
    _costController.dispose();
    _descriptionController.dispose();
    super.dispose();
  }

  void _submitExpense() {
    if (selectedProperty == null ||
        selectedExpenseType == null ||
        _costController.text.isEmpty ||
        _descriptionController.text.isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('Please fill all required fields')),
      );
      return;
    }

    final expense = Expense(
      id: '', // Will be generated by the server
      propertyId: selectedProperty!.id,
      type: selectedExpenseType!,
      description: _descriptionController.text,
      cost: double.tryParse(_costController.text) ?? 0.0,
      status: 'Pending',
    );

    context.read<ExpensesBloc>().add(AddExpense(expense));
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);

    return Scaffold(
      backgroundColor: theme.colorScheme.tertiary,
      appBar: AppBar(
        automaticallyImplyLeading: false,
        leading: IconButton(
          onPressed: () {
            Navigator.pop(context);
          },
          icon: SvgPicture.asset(SvgAssets.backOutline),
        ),
        backgroundColor: theme.colorScheme.tertiary,
        title: const Text("Add Expense"),
      ),
      body: Padding(
        padding: const EdgeInsets.all(16),
        child: Column(
          children: [
            Expanded(
              child: ListView(
                children: [
                  BlocBuilder<AllPropertyBloc, AllPropertyState>(
                    builder: (context, state) {
                      if (state is PropertyLoading) {
                        return AltTextField(
                          label: "Property",
                          hint: "Loading properties...",
                          type: AltFieldType.dropdown,
                          items: ["Loading..."],
                        );
                      }

                      if (state is PropertyLoaded) {
                        final propertyNames = state.properties
                            .map((p) => p.name)
                            .toList();

                        return AltTextField(
                          label: "Property",
                          hint:
                              selectedProperty?.name ??
                              "Select property to repair/renovate",
                          type: AltFieldType.dropdown,
                          items: propertyNames,
                          value: selectedProperty?.name,
                          onChanged: (value) {
                            setState(() {
                              selectedProperty = state.properties.firstWhere(
                                (p) => p.name == value,
                                orElse: () => state.properties.first,
                              );
                              selectedUnit =
                                  null; // Reset unit when property changes
                            });
                          },
                        );
                      }

                      return AltTextField(
                        label: "Property",
                        hint: "No properties available",
                        type: AltFieldType.dropdown,
                        items: ["No properties"],
                      );
                    },
                  ),
                  AltTextField(
                    label: "Select Unit",
                    hint: selectedUnit != null
                        ? selectedUnit!
                        : (selectedProperty != null
                              ? "Select unit to repair/renovate"
                              : "Select property first"),
                    type: AltFieldType.dropdown,
                    items: selectedProperty != null
                        ? List.generate(
                            selectedProperty!.units,
                            (index) => "Unit ${index + 1}",
                          )
                        : ["No property selected"],
                    value: selectedUnit,
                    onChanged: selectedProperty != null
                        ? (value) {
                            setState(() {
                              selectedUnit = value;
                            });
                          }
                        : null,
                  ),
                  AltTextField(
                    type: AltFieldType.dropdown,
                    label: "Expenses Type",
                    hint: selectedExpenseType ?? "Select expenses type",
                    value: selectedExpenseType,
                    items: [
                      "Cleaning & Renovation",
                      "Fix & Repairs",
                      "Staff Salary",
                      "Utitily & Bills",
                    ],
                    onChanged: (value) {
                      setState(() {
                        selectedExpenseType = value;
                      });
                    },
                  ),
                  AltTextField(
                    type: AltFieldType.text,
                    label: "Money Spent  (${context.watch<HomeBloc>().state.user?.currency})",
                    hint: "Enter amount spent",
                    onChanged: (value) {
                      _costController.text = value;
                    },
                  ),
                  AltTextField(
                    type: AltFieldType.multiline,
                    label: "Description",
                    hint: "Enter description",
                    maxLines: 4,
                    onChanged: (value) {
                      _descriptionController.text = value;
                    },
                  ),

                  const SizedBox(height: 20),

                  // Text("Add Photo of Expenses", style: theme.textTheme.titleMedium),

                  // const SizedBox(height: 10),

                  // Row(
                  //   children: List.generate(
                  //     3,
                  //     (index) => Container(
                  //       margin: const EdgeInsets.only(right: 10),
                  //       width: 90,
                  //       height: 80,
                  //       decoration: BoxDecoration(
                  //         borderRadius: BorderRadius.circular(10),
                  //         color: Colors.grey.shade300,
                  //       ),
                  //     ),
                  //   ),
                  // ),
                  const SizedBox(height: 30),
                ],
              ),
            ),
            BlocListener<ExpensesBloc, ExpensesState>(
              listener: (context, state) {
                if (state is ExpensesLoading) {
                  setState(() {
                    _isSubmitting = true;
                  });
                } else {
                  setState(() {
                    _isSubmitting = false;
                  });
                }

                if (state is ExpensesLoaded) {
                  // ScaffoldMessenger.of(context).showSnackBar(
                  //   const SnackBar(content: Text('Expense added successfully')),
                  // );
                  Navigator.pop(context);
                } else if (state is ExpensesError) {
                  ScaffoldMessenger.of(context).showSnackBar(
                    SnackBar(content: Text('Error: ${state.message}')),
                  );
                }
              },
              child: AppButton(
                title: _isSubmitting ? "Submitting..." : "Submit",
                onPressed: _isSubmitting ? null : _submitExpense,
              ),
            ),
          ],
        ),
      ),
    );
  }
}
